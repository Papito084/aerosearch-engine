class StopWordsFilter:
    """Configurable stop words filter supporting English, Spanish, and custom words."""

    def __init__(
        self,
        languages: list[str] | None = None,
        custom_words: set[str] | None = None,
        enabled: bool = True,
    ) -> None:
        self.enabled = enabled
        self._words: set[str] = set()

        if enabled:
            langs = languages or ["en", "es"]
            if "en" in langs:
                self._words.update(ENGLISH_STOP_WORDS)
            if "es" in langs:
                self._words.update(SPANISH_STOP_WORDS)
            if custom_words:
                self._words.update(w.lower() for w in custom_words)

    def is_stop_word(self, word: str) -> bool:
        """Check if a word is in the stop words set."""
        if not self.enabled:
            return False
        return word.lower() in self._words

    def add_words(self, words: set[str]) -> None:
        """Add additional stop words dynamically."""
        self._words.update(w.lower() for w in words)

    def remove_words(self, words: set[str]) -> None:
        """Remove stop words dynamically."""
        self._words.difference_update(w.lower() for w in words)

    def __len__(self) -> int:
        return len(self._words)
